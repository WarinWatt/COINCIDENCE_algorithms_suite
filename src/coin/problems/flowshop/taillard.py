def taillard_catalog():
    result=[]; number=1
    for count,jobs,machines in _GROUPS:
        for _ in range(count):
            result.append({"id":f"ta{number:03d}","jobs":jobs,"machines":machines,"seed":_SEEDS[number-1]}); number+=1
    return result

